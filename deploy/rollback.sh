#!/usr/bin/env bash
#
# Return the production site to the previous release.
#
#   rollback.sh            # the colour and tag recorded by the last deploy
#   rollback.sh <tag>      # redeploy a specific tag onto the idle colour
#
# Without an argument this is a pure upstream flip: the outgoing colour was
# left warm by deploy.sh, so traffic moves back with one graceful reload and no
# container is rebuilt. With a tag it behaves like a deploy of that tag, which
# is how a release older than the previous one is restored.
#
# The state file is updated either way, so a second rollback alternates back.

set -euo pipefail

APP_ROOT="${APP_ROOT:-/srv/apps/CreativityCenter}"
PUBLIC_PORT="${PUBLIC_PORT:-5517}"
BLUE_PORT="${BLUE_PORT:-9010}"
GREEN_PORT="${GREEN_PORT:-9011}"

SHARED_DIR="${APP_ROOT}/shared"
STATE_FILE="${SHARED_DIR}/deploy-state"
UPSTREAM_FILE="${SHARED_DIR}/nginx/upstream.conf"

log() { printf '[rollback] %s\n' "$*"; }
die() { printf '[rollback] error: %s\n' "$*" >&2; exit 1; }

port_for() {
    case "$1" in
        blue) printf '%s' "$BLUE_PORT" ;;
        green) printf '%s' "$GREEN_PORT" ;;
        *) die "unknown colour: $1" ;;
    esac
}

state_get() {
    grep -E "^$1=" "$STATE_FILE" 2>/dev/null | tail -n 1 | cut -d '=' -f 2- || true
}

[ -f "$STATE_FILE" ] || die "no deploy state at ${STATE_FILE} - nothing to roll back to"

ACTIVE="$(state_get ACTIVE_COLOR)"
PREVIOUS="$(state_get PREVIOUS_COLOR)"
PREVIOUS_TAG="$(state_get PREVIOUS_TAG)"
REQUESTED_TAG="${1:-}"

case "$PREVIOUS" in
    blue | green) ;;
    *) die "the recorded previous colour is not valid: '${PREVIOUS}'" ;;
esac

if [ -n "$REQUESTED_TAG" ]; then
    log "redeploying ${REQUESTED_TAG} onto the idle colour"
    exec "${APP_ROOT}/deploy/deploy.sh" "$REQUESTED_TAG"
fi

[ -n "$PREVIOUS_TAG" ] || die "the state file records no previous tag"
[ "$PREVIOUS" != "$ACTIVE" ] || die "the previous colour is the active one - nothing to roll back"

TARGET_PORT="$(port_for "$PREVIOUS")"

# A warm colour answers immediately. If it was stopped (a host reboot, a manual
# `compose stop`), bring it back on its recorded tag before moving traffic.
if ! curl -fsS -o /dev/null --max-time 5 "http://127.0.0.1:${TARGET_PORT}/up"; then
    log "${PREVIOUS} is not answering - starting it on ${PREVIOUS_TAG}"
    "${APP_ROOT}/deploy/deploy.sh" "$PREVIOUS_TAG"
    exit $?
fi

backup="$(mktemp)"
cp "$UPSTREAM_FILE" "$backup"

cat > "$UPSTREAM_FILE" <<EOF
# Generated by deploy/rollback.sh - do not edit by hand.
# Active colour: ${PREVIOUS} (127.0.0.1:${TARGET_PORT})
upstream cc_active {
    server 127.0.0.1:${TARGET_PORT};
    keepalive 32;
}
EOF

if ! output="$(nginx -t 2>&1)"; then
    cp "$backup" "$UPSTREAM_FILE"
    rm -f "$backup"
    printf '%s\n' "$output" >&2
    die "nginx rejected the rollback upstream - the previous file is restored"
fi
rm -f "$backup"

nginx -s reload
log "traffic is back on ${PREVIOUS} (${PREVIOUS_TAG})"

curl -fsS -o /dev/null --max-time 15 "http://127.0.0.1:${PUBLIC_PORT}/up" \
    || die "the public health route failed after the rollback"

printf 'ACTIVE_COLOR=%s\nACTIVE_TAG=%s\nPREVIOUS_COLOR=%s\nPREVIOUS_TAG=%s\n' \
    "$PREVIOUS" "$PREVIOUS_TAG" "$ACTIVE" "$(state_get ACTIVE_TAG)" > "${STATE_FILE}.tmp"
mv "${STATE_FILE}.tmp" "$STATE_FILE"

log "rollback complete - http://127.0.0.1:${PUBLIC_PORT} serves ${PREVIOUS_TAG}"