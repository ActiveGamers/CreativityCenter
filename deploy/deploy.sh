#!/usr/bin/env bash
#
# Zero-downtime blue/green release of the CreativityCenter production stack.
#
#   deploy.sh <image-tag>
#
# The invariant: the colour that serves traffic is never stopped, recreated or
# pointed away from before the other colour has proven it can serve. Every step
# that could fail happens while the active colour is still the upstream, and
# the only moment traffic moves is one graceful `nginx -s reload`, where the
# old workers finish the requests they already accepted.
#
# Order of operations:
#   1. resolve the idle colour and pull its images
#   2. bring it up and wait for its container health gate
#   3. wait for /up through its own loopback port (nginx -> fpm -> DB -> Redis)
#   4. migrate, and seed once on the very first release
#   5. flip the upstream, reload nginx
#   6. smoke test through the PUBLIC port and confirm the new colour answers
#   7. record the state; leave the outgoing colour warm for an instant rollback
#
# A failure before step 5 leaves the site on the old colour and stops the new
# one. A failure at or after step 5 puts the upstream back on the old colour.
#
# IMPORTANT (AGENTS.md section 5): no optimize/cache command is ever run here.

set -euo pipefail

APP_ROOT="${APP_ROOT:-/srv/apps/CreativityCenter}"
IMAGE_REPO="${IMAGE_REPO:-ghcr.io/activegamers/creativitycenter}"
WEB_REPO="${WEB_REPO:-ghcr.io/activegamers/creativitycenter-web}"
PUBLIC_PORT="${PUBLIC_PORT:-5517}"
BLUE_PORT="${BLUE_PORT:-9010}"
GREEN_PORT="${GREEN_PORT:-9011}"
DATA_NETWORK="${DATA_NETWORK:-creativitycenter-data}"
HEALTH_TIMEOUT="${HEALTH_TIMEOUT:-180}"

SHARED_DIR="${APP_ROOT}/shared"
DATA_DIR="${APP_ROOT}/data"
STATE_FILE="${SHARED_DIR}/deploy-state"
UPSTREAM_FILE="${SHARED_DIR}/nginx/upstream.conf"
COMPOSE_FILE="${APP_ROOT}/deploy/compose.prod.yaml"
DATA_COMPOSE_FILE="${APP_ROOT}/deploy/compose.data.yaml"

TAG="${1:-}"
FLIPPED=0
TARGET=""
ACTIVE=""

log() { printf '[deploy] %s\n' "$*"; }
warn() { printf '[deploy] warning: %s\n' "$*" >&2; }
die() { printf '[deploy] error: %s\n' "$*" >&2; exit 1; }

port_for() {
    case "$1" in
        blue) printf '%s' "$BLUE_PORT" ;;
        green) printf '%s' "$GREEN_PORT" ;;
        *) die "unknown colour: $1" ;;
    esac
}

other_colour() {
    [ "$1" = "blue" ] && printf 'green' || printf 'blue'
}

state_get() {
    grep -E "^$1=" "$STATE_FILE" 2>/dev/null | tail -n 1 | cut -d '=' -f 2- || true
}

state_write() {
    local active_color="$1" active_tag="$2" previous_color="$3" previous_tag="$4"

    printf 'ACTIVE_COLOR=%s\nACTIVE_TAG=%s\nPREVIOUS_COLOR=%s\nPREVIOUS_TAG=%s\n' \
        "$active_color" "$active_tag" "$previous_color" "$previous_tag" > "${STATE_FILE}.tmp"
    mv "${STATE_FILE}.tmp" "$STATE_FILE"
}

# Every compose call reads the same shared environment file, so the colour
# projects and the data project can never disagree about credentials. Values
# exported here (the image tags, the colour, the port) win over that file.
compose() {
    local colour="$1"
    shift

    COLOR="$colour" \
    HOST_PORT="$(port_for "$colour")" \
    APP_IMAGE="${IMAGE_REPO}:${TAG}" \
    WEB_IMAGE="${WEB_REPO}:${TAG}" \
    SHARED_DIR="$SHARED_DIR" \
    DATA_DIR="$DATA_DIR" \
    docker compose \
        --project-name "cc-${colour}" \
        --project-directory "$APP_ROOT" \
        --env-file "${SHARED_DIR}/.env" \
        --file "$COMPOSE_FILE" \
        "$@"
}

data_compose() {
    SHARED_DIR="$SHARED_DIR" DATA_DIR="$DATA_DIR" \
    docker compose \
        --project-name cc-data \
        --project-directory "$APP_ROOT" \
        --env-file "${SHARED_DIR}/.env" \
        --file "$DATA_COMPOSE_FILE" \
        "$@"
}

# Writes the upstream, validates the WHOLE host configuration, and only then
# reloads. A rejected file is restored before returning, so a bad release can
# never leave nginx without a valid configuration.
write_upstream() {
    local colour="$1" port backup output
    port="$(port_for "$colour")"
    backup="$(mktemp)"

    cp "$UPSTREAM_FILE" "$backup"

    cat > "$UPSTREAM_FILE" <<EOF
# Generated by deploy/deploy.sh - do not edit by hand.
# Active colour: ${colour} (127.0.0.1:${port})
upstream cc_active {
    server 127.0.0.1:${port};
    keepalive 32;
}
EOF

    if ! output="$(nginx -t 2>&1)"; then
        cp "$backup" "$UPSTREAM_FILE"
        rm -f "$backup"
        printf '%s\n' "$output" >&2
        die "nginx rejected the upstream for ${colour} - the previous file is restored"
    fi

    rm -f "$backup"
    nginx -s reload
    log "upstream now points at ${colour} (127.0.0.1:${port}), nginx reloaded"
}

wait_healthy() {
    local url="$1" deadline="$2" now
    now="$(date +%s)"
    deadline=$((now + deadline))

    while [ "$(date +%s)" -lt "$deadline" ]; do
        if curl -fsS -o /dev/null --max-time 5 "$url"; then
            return 0
        fi
        sleep 2
    done

    return 1
}

on_exit() {
    local code=$?
    [ "$code" -eq 0 ] && return 0

    if [ "$FLIPPED" -eq 1 ]; then
        warn "the release failed after the flip - putting traffic back on ${ACTIVE}"
        write_upstream "$ACTIVE" || warn "could not restore the upstream, run deploy/rollback.sh"
    elif [ -n "$TARGET" ]; then
        warn "the release failed before the flip - ${ACTIVE} never lost traffic"
        compose "$TARGET" stop || true
    fi

    exit "$code"
}
trap on_exit EXIT

# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------
[ -n "$TAG" ] || die "usage: deploy.sh <image-tag>"
[ -f "${SHARED_DIR}/.env" ] || die "${SHARED_DIR}/.env is missing - run deploy/provision.sh first"
[ -f "$COMPOSE_FILE" ] || die "$COMPOSE_FILE is missing"
[ -f "$UPSTREAM_FILE" ] || die "$UPSTREAM_FILE is missing - run deploy/provision.sh first"
command -v nginx >/dev/null 2>&1 || die "nginx is not installed on this host"

docker network inspect "$DATA_NETWORK" >/dev/null 2>&1 \
    || die "the ${DATA_NETWORK} network is missing - run deploy/provision.sh first"

# The stateful tier is owned by provisioning, not by a release: recreating MySQL
# here would interrupt the very traffic this script promises to protect.
data_compose ps --status running --services 2>/dev/null | grep -qx mysql \
    || die "the cc-data mysql service is not running - start it before deploying"
data_compose ps --status running --services 2>/dev/null | grep -qx redis \
    || die "the cc-data redis service is not running - start it before deploying"

ACTIVE="$(state_get ACTIVE_COLOR)"
case "$ACTIVE" in
    blue | green) ;;
    *) ACTIVE=blue; warn "no valid state file - assuming ${ACTIVE} is active" ;;
esac
TARGET="$(other_colour "$ACTIVE")"
ACTIVE_TAG="$(state_get ACTIVE_TAG)"

log "release ${TAG}: ${ACTIVE} is active, bringing up ${TARGET}"

# ---------------------------------------------------------------------------
# 1-2) Pull and start the idle colour
# ---------------------------------------------------------------------------
compose "$TARGET" pull --quiet
compose "$TARGET" up -d --wait --timeout "$HEALTH_TIMEOUT"

# ---------------------------------------------------------------------------
# 3) Health gate through the colour's own port, before it receives any traffic
# ---------------------------------------------------------------------------
TARGET_PORT="$(port_for "$TARGET")"
log "waiting for http://127.0.0.1:${TARGET_PORT}/up"
wait_healthy "http://127.0.0.1:${TARGET_PORT}/up" "$HEALTH_TIMEOUT" \
    || die "${TARGET} did not become healthy - the site stays on ${ACTIVE}"

# ---------------------------------------------------------------------------
# 4) Migrations, then the one-time seed
# ---------------------------------------------------------------------------
# --isolated takes a cache lock: the two colours share one schema, and a manual
# deploy running beside this one must not migrate at the same time.
log "running the pending migrations"
compose "$TARGET" exec -T app php artisan migrate --force --no-interaction --isolated

if [ ! -f "${SHARED_DIR}/.seeded" ]; then
    log "first release - seeding the school content"
    for seeder in MajorSeeder MajorCourseSeeder AchievementSeeder StatisticSeeder StaffMemberSeeder PostSeeder GalleryImageSeeder; do
        compose "$TARGET" exec -T app php artisan db:seed --force --no-interaction --class="$seeder"
    done
    # ContactMessageSeeder and AdmissionRequestSeeder are deliberately absent:
    # they invent visitor submissions, which must never reach production.
    touch "${SHARED_DIR}/.seeded"
fi

# ---------------------------------------------------------------------------
# 5) The flip
# ---------------------------------------------------------------------------
write_upstream "$TARGET"
FLIPPED=1

# ---------------------------------------------------------------------------
# 6) Smoke test through the public port
# ---------------------------------------------------------------------------
log "smoke testing http://127.0.0.1:${PUBLIC_PORT}"
wait_healthy "http://127.0.0.1:${PUBLIC_PORT}/up" 60 \
    || die "the public health route failed after the flip"
curl -fsS -o /dev/null --max-time 15 "http://127.0.0.1:${PUBLIC_PORT}/" \
    || die "the home page failed after the flip"

# The manifest is a static, per-release file: comparing it across the two ports
# proves the public port really serves the NEW colour, not a cached old worker.
public_manifest="$(curl -fsS --max-time 15 "http://127.0.0.1:${PUBLIC_PORT}/build/manifest.json")" \
    || die "could not read the manifest through the public port"
target_manifest="$(curl -fsS --max-time 15 "http://127.0.0.1:${TARGET_PORT}/build/manifest.json")" \
    || die "could not read the manifest from ${TARGET}"
[ "$public_manifest" = "$target_manifest" ] \
    || die "the public port does not serve ${TARGET} yet"

# ---------------------------------------------------------------------------
# 7) Record the state
# ---------------------------------------------------------------------------
state_write "$TARGET" "$TAG" "$ACTIVE" "${ACTIVE_TAG:-$TAG}"

log "release ${TAG} is live on ${TARGET} (127.0.0.1:${TARGET_PORT})"
log "public entry point: http://127.0.0.1:${PUBLIC_PORT}"
if [ -n "${ACTIVE_TAG:-}" ] && [ "$ACTIVE_TAG" != "$TAG" ]; then
    log "${ACTIVE} stays warm on ${ACTIVE_TAG} - deploy/rollback.sh returns to it instantly"
fi